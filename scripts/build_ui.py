"""Build one layered CSS entry point from legacy components and product tokens."""
from pathlib import Path
import re

public = Path(__file__).resolve().parents[1] / 'site'
legacy = '\n'.join((public / name).read_text(encoding='utf-8') for name in
    ('styles.css', 'discovery.css', 'refinements.css', 'experience.css'))
product = (public / 'product-ui.css').read_text(encoding='utf-8')
assert not re.search(r'@import\b|@charset\b', legacy + product)
bundle = '/* Generated by scripts/build_ui.py. Edit product-ui.css for the product design. */\n@layer legacy, product;\n@layer legacy {\n' + legacy + '\n}\n@layer product {\n' + product + '\n}\n'
(public / 'app-ui.css').write_text(bundle,encoding='utf-8')
print(f'app-ui.css: {len(bundle.encode("utf-8")):,} bytes; one stylesheet entry point')
